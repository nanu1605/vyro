#!/usr/bin/env python3
"""Writes THIRD_PARTY_NOTICES.md: PawnIO (bundled installer, embedded modules) plus every Rust
crate compiled into the Windows app and the npm packages bundled into its UI.

    python3 scripts/third_party.py          # regenerate
    python3 scripts/third_party.py --check  # CI: fail if the file is out of date
"""

import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
TARGET = "x86_64-pc-windows-msvc"
# npm packages whose code ends up in dist/ (the UI bundle). Svelte is a devDependency but its
# runtime is compiled into the bundle.
UI_PACKAGES = ["svelte", "@tauri-apps/api"]

HEADER = """# Third-party notices

Vyro is licensed under MIT OR Apache-2.0 (see `LICENSE-MIT`, `LICENSE-APACHE`). It includes or
ships the third-party software below. This file is generated by `scripts/third_party.py`; do
not edit it by hand.

## PawnIO

- **PawnIO installer** (`pawnio\\PawnIO_setup.exe`, unmodified, signed by its author) from
  <https://github.com/namazso/PawnIO.Setup>. The PawnIO driver is licensed under GPL-2.0 with
  an exception for independent programs that communicate with it only through its IOCTL
  interface, which is how Vyro uses it. Driver source: <https://github.com/namazso/PawnIO>.
- **PawnIO modules** (`AMDFamily17.bin`, `LpcIO.bin`, `SmbusPIIX4.bin`, `RyzenSMU.bin`, `Nvidia.bin`,
  embedded in `vyro.exe`, unmodified) from <https://github.com/namazso/PawnIO.Modules>,
  licensed under LGPL-2.1-or-later; the license text is installed as
  `COPYING-PawnIO-modules`. They are loaded into the separately installed driver at run time.
"""


def crates():
    meta = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
            cwd=ROOT,
        )
    )
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = next(p["id"] for p in meta["packages"] if p["name"] == "vyro" and p["source"] is None)
    seen, stack = set(), [root]
    while stack:
        node = nodes[stack.pop()]
        for dep in node["deps"]:
            # Runtime code only: skip dev- and build-dependencies.
            if not any(k["kind"] is None for k in dep["dep_kinds"]):
                continue
            if dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                stack.append(dep["pkg"])
    out = []
    for pid in seen:
        p = pkgs[pid]
        if p["source"] is None:  # our own crates
            continue
        out.append((p["name"], p["version"], p.get("license") or "see repository", p.get("repository") or ""))
    return sorted(out)


def npm():
    out = []
    for name in UI_PACKAGES:
        pj = json.loads((ROOT / "node_modules" / name / "package.json").read_text())
        repo = pj.get("repository")
        if isinstance(repo, dict):
            repo = repo.get("url", "")
        out.append((name, pj["version"], pj.get("license", "see repository"), repo or ""))
    return out


def table(rows):
    lines = ["| Package | Version | License | Source |", "|---|---|---|---|"]
    for name, version, lic, repo in rows:
        lines.append(f"| {name} | {version} | {lic} | {repo} |")
    return "\n".join(lines)


def render():
    rust = crates()
    return (
        HEADER
        + f"\n## Rust crates ({len(rust)})\n\nCompiled into `vyro.exe` for Windows. Full license texts are in each crate's source"
        + " package (crates.io) and repository.\n\n"
        + table(rust)
        + "\n\n## UI packages\n\nBundled into the app's user interface.\n\n"
        + table(npm())
        + "\n"
    )


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("THIRD_PARTY_NOTICES.md is out of date: run python3 scripts/third_party.py")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
