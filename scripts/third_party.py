#!/usr/bin/env python3
"""Writes THIRD_PARTY_NOTICES.md (PawnIO, PresentMon and a table of every Rust crate compiled
into the Windows app and the npm packages bundled into its UI) and THIRD_PARTY_LICENSES.md (their full
license texts, taken from each package's source; identical texts are listed once).

    python3 scripts/third_party.py          # regenerate
    python3 scripts/third_party.py --check  # CI: fail if either file is out of date
"""

import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
LICENSES_OUT = ROOT / "THIRD_PARTY_LICENSES.md"
# Standard texts (SPDX license-list-data) for the few packages that ship none.
FALLBACK_DIR = ROOT / "scripts" / "licenses"
LICENSE_FILE = re.compile(r"^(LICEN[CS]E|COPYING|NOTICE|UNLICENSE)", re.I)
TARGET = "x86_64-pc-windows-msvc"
# npm packages whose code ends up in dist/ (the UI bundle) or in the phone app the relay serves
# (relay/public, 1.4: jsQR reads pairing codes). Svelte is a devDependency but its runtime is
# compiled into both.
UI_PACKAGES = ["svelte", "@tauri-apps/api", "three", "@lucide/svelte", "jsqr"]

HEADER = """# Third-party notices

Vyro is licensed under MIT OR Apache-2.0 (see `LICENSE-MIT`, `LICENSE-APACHE`). It includes or
ships the third-party software below; their full license texts are in
`THIRD_PARTY_LICENSES.md`. This file is generated by `scripts/third_party.py`; do not edit it by
hand.

## PawnIO

- **PawnIO installer** (`pawnio\\PawnIO_setup.exe`, unmodified, signed by its author) from
  <https://github.com/namazso/PawnIO.Setup>. The PawnIO driver is licensed under GPL-2.0 with
  an exception for independent programs that communicate with it only through its IOCTL
  interface, which is how Vyro uses it. Driver source: <https://github.com/namazso/PawnIO>.
- **PawnIO modules** (`AMDFamily17.bin`, `LpcIO.bin`, `SmbusPIIX4.bin`, `RyzenSMU.bin`, `Nvidia.bin`,
  embedded in `vyro.exe`, unmodified) from <https://github.com/namazso/PawnIO.Modules>,
  licensed under LGPL-2.1-or-later; the license text is installed as
  `COPYING-PawnIO-modules`. They are loaded into the separately installed driver at run time.

## PresentMon

- **PresentMon console application** (`PresentMon.exe`, version 2.6.0, unmodified, signed by
  Intel) from <https://github.com/GameTechDev/PresentMon>, licensed under MIT (text in
  `THIRD_PARTY_LICENSES.md`). The sensor service runs it to measure game frame rates.
"""


def crates():
    meta = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
            cwd=ROOT,
        )
    )
    pkgs = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = next(p["id"] for p in meta["packages"] if p["name"] == "vyro" and p["source"] is None)
    seen, stack = set(), [root]
    while stack:
        node = nodes[stack.pop()]
        for dep in node["deps"]:
            # Runtime code only: skip dev- and build-dependencies.
            if not any(k["kind"] is None for k in dep["dep_kinds"]):
                continue
            if dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                stack.append(dep["pkg"])
    out = []
    for pid in seen:
        p = pkgs[pid]
        if p["source"] is None:  # our own crates
            continue
        out.append((p["name"], p["version"], p.get("license") or "see repository", p.get("repository") or ""))
    return sorted(out)


def crate_sources():
    """(name, version, license, authors, source dir) for every crate in `crates()`."""
    meta = json.loads(
        subprocess.check_output(
            ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
            cwd=ROOT,
        )
    )
    wanted = {(n, v) for n, v, _, _ in crates()}
    out = []
    for p in meta["packages"]:
        if (p["name"], p["version"]) in wanted:
            out.append(
                (p["name"], p["version"], p.get("license") or "", p.get("authors") or [],
                 pathlib.Path(p["manifest_path"]).parent)
            )
    return sorted(out, key=lambda t: (t[0], t[1]))


def npm():
    out = []
    for name in UI_PACKAGES:
        pj = json.loads((ROOT / "node_modules" / name / "package.json").read_text())
        repo = pj.get("repository")
        if isinstance(repo, dict):
            repo = repo.get("url", "")
        out.append((name, pj["version"], pj.get("license", "see repository"), repo or ""))
    return out


def table(rows):
    lines = ["| Package | Version | License | Source |", "|---|---|---|---|"]
    for name, version, lic, repo in rows:
        lines.append(f"| {name} | {version} | {lic} | {repo} |")
    return "\n".join(lines)


def render():
    rust = crates()
    return (
        HEADER
        + f"\n## Rust crates ({len(rust)})\n\nCompiled into `vyro.exe` for Windows. Full license texts are in each crate's source"
        + " package (crates.io) and repository.\n\n"
        + table(rust)
        + "\n\n## UI packages\n\nBundled into the app's user interface.\n\n"
        + table(npm())
        + "\n"
    )


def license_files(d):
    return sorted(f for f in d.iterdir() if f.is_file() and LICENSE_FILE.match(f.name))


def fallback(name, license, authors):
    """Standard text for a package without license files: MIT when offered, else the first
    license named, with the placeholder copyright line filled from the package metadata."""
    for spdx in ("MIT", "Apache-2.0", "BSD-3-Clause", "MPL-2.0"):
        if spdx in license:
            break
    else:
        sys.exit(f"{name}: no license file and no fallback text for {license!r}")
    if spdx == "Apache-2.0":
        return spdx, (ROOT / "LICENSE-APACHE").read_text()
    text = (FALLBACK_DIR / f"{spdx}.txt").read_text()
    who = ", ".join(a.split(" <")[0] for a in authors) or f"the {name} authors"
    text = re.sub(r"<year> <(copyright holders|owner)>", who, text)
    return spdx, text


def render_licenses():
    # text → (file label, [package@version])
    texts = {}

    def add(pkg, label, text):
        text = text.replace("\r\n", "\n").strip() + "\n"
        key = re.sub(r"\s+", " ", text)
        entry = texts.setdefault(key, [label, text, []])
        entry[2].append(pkg)

    for name, version, license, authors, d in crate_sources():
        files = license_files(d)
        if files:
            for f in files:
                add(f"{name} {version}", f.name, f.read_text(errors="replace"))
        else:
            spdx, text = fallback(name, license, authors)
            add(f"{name} {version}", f"{spdx} (standard text; the package ships none)", text)
    add("PresentMon 2.6.0 (bundled executable)", "LICENSE.txt", (FALLBACK_DIR / "PresentMon.txt").read_text())
    for name in UI_PACKAGES:
        d = ROOT / "node_modules" / name
        version = json.loads((d / "package.json").read_text())["version"]
        for f in license_files(d):
            add(f"{name} {version} (npm)", f.name, f.read_text(errors="replace"))

    out = [
        "# Third-party licenses",
        "",
        "Full license texts of the Rust crates and npm packages listed in",
        "`THIRD_PARTY_NOTICES.md`, as shipped in each package's source. Identical texts are listed",
        "once with every package that uses them. PawnIO's texts are `COPYING-PawnIO-modules` and",
        "<https://github.com/namazso/PawnIO>. Generated by `scripts/third_party.py`; do not edit it",
        "by hand.",
        "",
    ]
    for i, (label, text, pkgs) in enumerate(sorted(texts.values(), key=lambda e: (e[2][0], e[0])), 1):
        # A fence longer than any tilde run the text itself starts a line with.
        fence = "~" * max([4] + [len(m) + 1 for m in re.findall(r"^~+", text, re.M)])
        out += [f"## {i}. {label}", "", "Used by: " + ", ".join(pkgs), "", fence + "text", text.rstrip("\n"), fence, ""]
    return "\n".join(out)


def main():
    outputs = [(OUT, render()), (LICENSES_OUT, render_licenses())]
    if "--check" in sys.argv:
        for path, text in outputs:
            if not path.exists() or path.read_text() != text:
                sys.exit(f"{path.name} is out of date: run python3 scripts/third_party.py")
        return
    for path, text in outputs:
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
