/** The pixels as markup for Logo.svelte (its `pixels`), the ink ones in `--logo-ink`. */
const markup = (ps: readonly Pixel[]) =>
  ps
    .map(([x, y, s, c, o]) => {
      const fill = c === 1 ? CYAN : c === 2 ? MAGENTA : 'var(--logo-ink, #fff)';
      return `<rect x="${x}" y="${y}" width="${s}" height="${s}" fill="${fill}" opacity="${o / 100}"/>`;
    })
    .join('');

export const PIXELS = { mark: markup(SCATTER.mark), word: markup(SCATTER.word) };
