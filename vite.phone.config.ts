/// <reference types="vitest/config" />
import { createHash } from 'node:crypto';
import { readdirSync } from 'node:fs';
import { join, relative } from 'node:path';
import { defineConfig, type Plugin } from 'vite';
import { svelte } from '@sveltejs/vite-plugin-svelte';

// The phone app (1.4): its own build into relay/public, which the relay serves. It is not part
// of the desktop app's installer. `pnpm build:phone`.

const PUBLIC = 'src/phone/public';

function files(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? files(join(dir, e.name)) : [`/${relative(PUBLIC, join(dir, e.name)).replace(/\\/g, '/')}`],
  );
}

/** The page as `index.html`, and a service worker that keeps the app's files for opening
 * offline (the page itself is fetched fresh whenever there is a network, so updates arrive). */
function installable(): Plugin {
  return {
    name: 'vyro-phone-installable',
    apply: 'build',
    // After Vite has put the page in the bundle.
    enforce: 'post',
    generateBundle(_, bundle) {
      const page = bundle['phone.html'];
      if (page) page.fileName = 'index.html';
      const all = ['/', ...Object.values(bundle).map((f) => `/${f.fileName}`), ...files(PUBLIC)]
        .filter((f) => f !== '/index.html')
        .sort();
      const version = createHash('sha256').update(all.join('\n')).digest('hex').slice(0, 12);
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: `// Vyro phone app: keeps its files for opening offline (generated by vite.phone.config.ts).
const CACHE = 'vyro-${version}';
const FILES = ${JSON.stringify(all)};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin) return;
  if (url.pathname.startsWith('/pc/') || url.pathname.startsWith('/phone/')) return;
  if (e.request.mode === 'navigate') {
    // The page fresh when there is a network (a new version), the kept one when not. The
    // address's fragment (a pairing link) never reaches here: browsers do not send it.
    e.respondWith(fetch(e.request).catch(() => caches.match('/')));
    return;
  }
  e.respondWith(caches.match(e.request).then((r) => r || fetch(e.request)));
});
`,
      });
    },
  };
}

export default defineConfig({
  plugins: [svelte(), installable()],
  publicDir: PUBLIC,
  clearScreen: false,
  build: {
    outDir: 'relay/public',
    emptyOutDir: true,
    target: 'es2022',
    sourcemap: false,
    rollupOptions: { input: { phone: 'phone.html' } },
  },
});
