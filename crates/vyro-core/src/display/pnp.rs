//! Common EDID PNP manufacturer ids. Unknown ids are shown as the raw three letters.

pub fn vendor(id: &str) -> Option<&'static str> {
    Some(match id {
        "AAC" | "ACR" => "Acer",
        "ACI" | "AUS" => "ASUS",
        "AOC" => "AOC",
        "APP" => "Apple",
        "AUO" => "AU Optronics",
        "BNQ" => "BenQ",
        "BOE" => "BOE",
        "CMN" => "Innolux",
        "CMO" => "Chi Mei",
        "CSO" => "CSOT",
        "DEL" => "Dell",
        "ENC" | "EIZ" => "EIZO",
        "FUS" => "Fujitsu",
        "GBT" => "Gigabyte",
        "GSM" => "LG Electronics",
        "HKC" => "HKC",
        "HPN" | "HWP" => "HP",
        "HSD" => "HannStar",
        "IVM" => "iiyama",
        "IVO" => "InfoVision",
        "KTC" => "KTC",
        "LEN" => "Lenovo",
        "LGD" => "LG Display",
        "MEI" => "Panasonic",
        "MSI" => "MSI",
        "NEC" => "NEC",
        "PHL" => "Philips",
        "SAM" => "Samsung",
        "SDC" => "Samsung Display",
        "SEC" => "Seiko Epson",
        "SHP" => "Sharp",
        "SNY" => "Sony",
        "TMX" => "Tianma",
        "TOS" => "Toshiba",
        "VIZ" => "Vizio",
        "VSC" => "ViewSonic",
        "XMI" => "Xiaomi",
        _ => return None,
    })
}
